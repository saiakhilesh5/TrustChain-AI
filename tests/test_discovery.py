import textwrap

from trustchain.discovery.inventory import discover


def _write(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(textwrap.dedent(content).lstrip("\n"), encoding="utf-8")


def test_npm_package_lock_discovery(tmp_path):
    _write(tmp_path / "package.json", """
    {
      "name": "demo-app",
      "version": "1.0.0",
      "license": "MIT",
      "dependencies": {"lodash": "^4.17.21"}
    }
    """)
    _write(tmp_path / "package-lock.json", """
    {
      "lockfileVersion": 3,
      "packages": {
        "": {"name": "demo-app", "version": "1.0.0"},
        "node_modules/lodash": {
          "version": "4.17.21",
          "resolved": "https://registry.npmjs.org/lodash/-/lodash-4.17.21.tgz",
          "integrity": "sha512-v2"
        }
      }
    }
    """)

    inv = discover(str(tmp_path))
    data = inv.to_dict()
    assert data["stats"]["total"] == 2
    assert data["stats"]["direct"] == 2
    lodash = next(c for c in data["components"] if c["name"] == "lodash")
    assert lodash["resolved_url"].startswith("https://registry.npmjs.org")


def test_yarn_berry_lock_discovery(tmp_path):
    _write(tmp_path / "package.json", """
    {
      "name": "demo",
      "version": "1.0.0",
      "dependencies": {"chalk": "^5.0.0"}
    }
    """)
    _write(tmp_path / "yarn.lock", """
    # This file is generated by running "yarn install" inside your project.

    __metadata:
      version: 10

    "chalk@npm:^5.0.0":
      version: 5.3.0
      resolution: "chalk@npm:5.3.0"
      dependencies:
        "ansi-styles": "npm:^6.1.0"
      checksum: 10c0/abc
      languageName: node
      linkType: hard

    "ansi-styles@npm:^6.1.0":
      version: 6.2.1
      resolution: "ansi-styles@npm:6.2.1"
      checksum: 10c0/def
      languageName: node
      linkType: hard
    """)

    inv = discover(str(tmp_path))
    data = inv.to_dict()
    assert data["stats"]["total"] == 3
    chalk = next(c for c in data["components"] if c["name"] == "chalk")
    ansi = next(c for c in data["components"] if c["name"] == "ansi-styles")
    assert chalk["scope"] == "direct"
    assert ansi["scope"] == "transitive"
    assert ansi["key"] in chalk["resolved_deps"]
    assert chalk["key"] in ansi["required_by"]


def test_yarn_v1_lock_discovery(tmp_path):
    _write(tmp_path / "package.json", """
    {"name": "demo", "version": "1.0.0", "dependencies": {"ms": "^2.1.1"}}
    """)
    _write(tmp_path / "yarn.lock", """
    # THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
    # yarn lockfile v1


    ms@^2.1.1:
      version "2.1.3"
      resolved "https://registry.yarnpkg.com/ms/-/ms-2.1.3.tgz#567f02c07d7044a1"
      integrity sha512-abc

    safe-buffer@~5.2.0:
      version "5.2.1"
      resolved "https://registry.yarnpkg.com/safe-buffer/-/safe-buffer-5.2.1.tgz"
      integrity sha512-def
    """)

    inv = discover(str(tmp_path))
    data = inv.to_dict()
    ms = next(c for c in data["components"] if c["name"] == "ms")
    assert ms["version"] == "2.1.3"
    assert ms["integrity"].startswith("sha512")
    assert data["stats"]["direct"] == 2  # demo + ms


def test_pip_requirements_discovery(tmp_path):
    _write(tmp_path / "requirements.txt", """
    Flask==3.0.0
    requests>=2.31.0
    # comment line
    -r other.txt
    """)

    inv = discover(str(tmp_path))
    data = inv.to_dict()
    by_name = {c["name"]: c for c in data["components"] if c["ecosystem"] == "pypi"}
    assert by_name["flask"]["version"] == "3.0.0"
    assert by_name["flask"]["scope"] == "direct"
    assert by_name["requests"]["version"] == "unknown"  # unpinned range
    assert by_name["requests"]["origin"]["line"] == 2


def test_ros_package_xml_discovery(tmp_path):
    _write(tmp_path / "pkg_a" / "package.xml", """
    <?xml version="1.0"?>
    <package format="3">
      <name>pkg_a</name>
      <version>1.2.3</version>
      <license>Apache 2.0</license>
      <maintainer email="a@example.com">A</maintainer>
      <url type="repository">https://example.com/repo</url>
      <exec_depend>pkg_b</exec_depend>
    </package>
    """)
    _write(tmp_path / "pkg_b" / "package.xml", """
    <?xml version="1.0"?>
    <package format="3">
      <name>pkg_b</name>
      <version>0.1.0</version>
      <license>BSD</license>
      <exec_depend>external_ros_dep</exec_depend>
    </package>
    """)

    inv = discover(str(tmp_path))
    data = inv.to_dict()
    a = next(c for c in data["components"] if c["name"] == "pkg_a")
    b = next(c for c in data["components"] if c["name"] == "pkg_b")
    assert a["version"] == "1.2.3"
    assert b["key"] in a["resolved_deps"]
    assert a["key"] in b["required_by"]
    assert "external_ros_dep" in b["depends_on"]
    assert len(b["resolved_deps"]) == 0  # external, no version info
